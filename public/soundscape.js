// Soundscape panel (Mike, Nov 16): mood wheel, environment, weather and intensity, layer chips, favourites, and the
// DM's master volume and output. Shared by the DM and the Music Co-DM (the DM page opened with the music key).
// The server holds the state (state.soundscape, src/soundscape.js); this only draws it and sends sound:* events.
(() => {
  const { esc } = Stage;
  const MOOD = {
    calm: { icon: '🍃', name: 'Calm', hue: 160 }, happy: { icon: '☀️', name: 'Happy', hue: 48 },
    funny: { icon: '🤪', name: 'Funny', hue: 300 }, epic: { icon: '⚔️', name: 'Epic', hue: 18 },
    sad: { icon: '💧', name: 'Sad', hue: 215 }, creepy: { icon: '🕸', name: 'Creepy', hue: 270 },
    tense: { icon: '💓', name: 'Tense', hue: 350 }, mystic: { icon: '🔮', name: 'Mystic', hue: 250 },
    magical: { icon: '✨', name: 'Magical', hue: 190 },
  };
  const ENV = {
    forest: '🌲 Forest', town: '🏘 Town', tavern: '🍺 Tavern', dungeon: '🗝 Dungeon', cave: '🪨 Cave', coast: '🌊 Coast', camp: '🏕 Camp',
  };
  const WEATHER = ['☀️ Clear', '🌦 Light rain', '🌧 Rain', '🌧 Heavy rain', '⛈ Storm'];
  const OUTPUTS = [['auto', 'Auto'], ['tv', '📺 TV'], ['laptop', '💻 Laptop']];
  const LAYER_MAX = 6;
  const step = (w = {}) => (!w.kind || w.kind === 'none' ? 0 : w.kind === 'storm' ? 4 : w.kind === 'rain' ? Math.max(1, Math.min(3, w.intensity || 2)) : -1);

  const HTML = `
    <h3>🎧 Soundscape <button class="btn small" data-ss="stop" title="Fade the soundscape out">■ Stop</button></h3>
    <p class="note" data-el="where"></p>
    <div class="ss-auto" data-el="auto" hidden></div>
    <p class="note ss-lock-note" data-el="lockNote" hidden>🔒 The DM has locked the soundscape. Your controls come back when the DM unlocks it.</p>
    <div class="ss-body">
      <div class="ss-top">
        <div class="ss-wheel" data-el="wheel" role="group" aria-label="Mood wheel">
          <div class="ss-hub" data-el="hub"><i></i><b>No mood</b><small>Pick a mood</small></div>
        </div>
        <div class="ss-side">
          <h4>Environment</h4>
          <div class="ss-envs" data-el="envs"></div>
          <label class="slider">Weather <input type="range" min="0" max="4" step="1" data-el="weather" aria-label="Weather, sun to storm"> <b data-el="weatherName"></b></label>
          <label class="slider">Intensity <input type="range" min="0" max="1" step="0.05" data-el="density" aria-label="Intensity, sparse to dense"> <b data-el="densityName"></b></label>
        </div>
      </div>
      <h4>Layers <span class="note" data-el="layerCount"></span></h4>
      <div class="ss-chips" data-el="layers"></div>
      <div class="row"><select data-el="addSel" class="grow" aria-label="Sound to add"></select><button class="btn" data-ss="add">+ Layer</button></div>
      <h4>Favourites</h4>
      <div class="ss-chips" data-el="favs"></div>
      <div class="row"><input data-el="favName" class="grow" maxlength="40" placeholder="Name this soundscape (optional)"><button class="btn" data-ss="fav">☆ Save</button></div>
    </div>
    <div class="ss-dm" data-el="dm">
      <h4>Output <span class="note">DM only</span></h4>
      <label class="slider">🔊 Master <input type="range" min="0" max="1" step="0.05" data-el="master" aria-label="Master volume"></label>
      <div class="ss-seg" data-el="outputs" role="group" aria-label="Where the sound plays"></div>
      <label class="chk"><input type="checkbox" data-el="autoCombat"> Combat shifts the mood to Epic (and back after)</label>
      <label class="chk"><input type="checkbox" data-el="lock"> 🔒 Lock the soundscape (the Music Co-DM can only watch)</label>
    </div>
    <p class="note" data-el="by"></p>
    <p class="note">Built-in sounds are PLACEHOLDER stand-ins generated by the laptop. Upload real loops under Scene › Stage and music and they appear in the layer list.</p>`;

  window.Soundscape = {
    mount(root, { emit, role = () => null }) {
      root.innerHTML = HTML;
      const el = (n) => root.querySelector(`[data-el="${n}"]`);
      // Mood wheel: nine moods round a hub that shows the one playing.
      const ids = Object.keys(MOOD);
      el('wheel').insertAdjacentHTML('beforeend', ids.map((m, i) => `<button class="ss-mood" data-mood="${m}" style="--a:${(360 / ids.length) * i - 90}deg;--h:${MOOD[m].hue}" title="${MOOD[m].name}" aria-pressed="false"><i>${MOOD[m].icon}</i><span>${MOOD[m].name}</span></button>`).join(''));
      el('envs').innerHTML = Object.entries(ENV).map(([k, v]) => `<button class="btn ss-env" data-env="${k}" aria-pressed="false">${v}</button>`).join('');
      el('outputs').innerHTML = OUTPUTS.map(([k, v]) => `<button class="btn small" data-output="${k}" aria-pressed="false">${v}</button>`).join('');

      let last = null;
      root.addEventListener('click', (ev) => {
        const b = ev.target.closest('button');
        if (!b || !last) return;
        const d = b.dataset;
        const ss = last.soundscape;
        if (d.mood) emit('sound:mood', { mood: ss.mood === d.mood ? null : d.mood });
        else if (d.env) emit('sound:env', { env: d.env });
        else if (d.output) emit('sound:output', { output: d.output });
        else if (d.rm) emit('sound:layer:remove', { id: d.rm });
        else if (d.favLoad) emit('sound:fav:load', { id: d.favLoad });
        else if (d.favDel) emit('sound:fav:delete', { id: d.favDel });
        else if (d.ss === 'stop') emit('sound:stop');
        else if (d.ss === 'undoAuto') emit('sound:auto:undo');
        else if (d.ss === 'add' && el('addSel').value) emit('sound:layer:add', { id: el('addSel').value });
        else if (d.ss === 'fav') { emit('sound:fav:save', { name: el('favName').value }); el('favName').value = ''; }
      });
      root.addEventListener('input', (ev) => {
        const t = ev.target;
        if (t.dataset.vol) emit('sound:layer:volume', { id: t.dataset.vol, volume: t.value });
        else if (t === el('density')) emit('sound:density', { value: t.value });
        else if (t === el('master')) emit('sound:master', { value: t.value });
      });
      root.addEventListener('change', (ev) => {
        const t = ev.target;
        if (t === el('weather')) emit('sound:weather', { step: t.value });
        else if (t === el('autoCombat')) emit('sound:autocombat', { on: t.checked });
        else if (t === el('lock')) emit('sound:lock', { on: t.checked });
      });

      const setVal = (input, v) => { if (document.activeElement !== input) input.value = v; };
      let layerKey = null;
      let favKey = null;
      let shown = new Set(); // chips drawn last time, so only new ones pop in
      let hubMood;
      return function render(s) {
        last = s;
        const ss = s.soundscape;
        const au = s.audio;
        if (!ss || !au) return;
        const helper = role() === 'music';
        const locked = helper && ss.locked;
        root.classList.toggle('ss-locked', locked);
        root.classList.toggle('ss-on', !!ss.on);
        el('lockNote').hidden = !locked;
        el('dm').hidden = helper;

        // Mood wheel and its hub. The hub pops when the mood changes.
        root.querySelectorAll('[data-mood]').forEach((b) => {
          const on = ss.on && b.dataset.mood === ss.mood;
          b.classList.toggle('on', on);
          b.setAttribute('aria-pressed', String(on));
        });
        const cur = ss.on ? ss.mood : null;
        if (cur !== hubMood) {
          hubMood = cur;
          const m = MOOD[cur];
          const hub = el('hub');
          hub.style.setProperty('--h', m ? m.hue : 40);
          hub.innerHTML = m ? `<i>${m.icon}</i><b>${m.name}</b><small>PLACEHOLDER music</small>` : '<i>🎧</i><b>No mood</b><small>Pick a mood</small>';
          hub.classList.remove('pop');
          void hub.offsetWidth; // restart the animation
          hub.classList.add('pop');
        }
        root.querySelectorAll('[data-env]').forEach((b) => {
          const on = ss.on && b.dataset.env === ss.env;
          b.classList.toggle('on', on);
          b.setAttribute('aria-pressed', String(on));
        });

        // Weather is the world's (travel and sight read it), so only the DM moves it.
        const w = step(s.weather);
        const wIn = el('weather');
        wIn.disabled = helper;
        wIn.title = helper ? 'The DM sets the weather' : '';
        if (w >= 0) setVal(wIn, w);
        el('weatherName').textContent = w >= 0 ? WEATHER[w] : `${s.weather.kind} (set by the DM)`;
        setVal(el('density'), ss.density);
        el('densityName').textContent = ss.density < 0.34 ? 'Sparse' : ss.density < 0.67 ? 'Medium' : 'Dense';

        // Layer chips: the soundscape's own layers (removable, each with a volume), then what the weather adds.
        const tracks = [...(au.loops || []), ...(au.library || [])];
        const nameOf = (id) => tracks.find((t) => t.id === id)?.name || id;
        const weatherIds = (au.mix || []).filter((m) => m.ss && !ss.layers.some((l) => l.id === m.id)).map((m) => m.id);
        const lk = `${ss.on}|${ss.layers.map((l) => l.id).join()}|${weatherIds.join()}|${tracks.map((t) => t.id).join()}`;
        if (lk !== layerKey) {
          layerKey = lk;
          const now = new Set([...ss.layers.map((l) => l.id), ...weatherIds]);
          el('layers').innerHTML = ss.layers.map((l) => `<span class="ss-chip ${shown.has(l.id) ? '' : 'enter'} ${ss.on ? '' : 'idle'}">
              <b>${esc(nameOf(l.id))}</b>
              <input type="range" min="0" max="1" step="0.05" data-vol="${esc(l.id)}" aria-label="${esc(nameOf(l.id))} volume">
              <button class="ss-x" data-rm="${esc(l.id)}" title="Remove this layer" aria-label="Remove ${esc(nameOf(l.id))}">✕</button>
            </span>`).join('')
            + weatherIds.map((id) => `<span class="ss-chip weather ${shown.has(id) ? '' : 'enter'}" title="Added by the weather"><b>🌧 ${esc(nameOf(id))}</b></span>`).join('')
            || '<p class="note">No layers. Pick an environment, or add a sound below.</p>';
          shown = now;
          el('addSel').innerHTML = '<option value="">Add a sound…</option>' + tracks.filter((t) => !ss.layers.some((l) => l.id === t.id))
            .map((t) => `<option value="${esc(t.id)}">${esc(t.name)}</option>`).join('');
        }
        for (const l of ss.layers) { const i = el('layers').querySelector(`[data-vol="${CSS.escape(l.id)}"]`); if (i) setVal(i, l.volume); }
        el('layerCount').textContent = `${ss.layers.length} of ${LAYER_MAX}`;
        el('addSel').disabled = ss.layers.length >= LAYER_MAX;

        const fk = ss.favs.map((f) => `${f.id}:${f.name}`).join();
        if (fk !== favKey) {
          favKey = fk;
          el('favs').innerHTML = ss.favs.map((f) => `<span class="ss-chip fav enter">
              <button class="ss-fav" data-fav-load="${esc(f.id)}" title="Play this soundscape">${f.mood ? MOOD[f.mood]?.icon || '' : '🎧'} ${esc(f.name)}</button>
              <button class="ss-x" data-fav-del="${esc(f.id)}" title="Forget this favourite" aria-label="Forget ${esc(f.name)}">✕</button>
            </span>`).join('') || '<p class="note">Save the scene you hear to call it back in one tap.</p>';
        }

        // The last automatic change, with its one-tap override.
        const a = ss.auto;
        el('auto').hidden = !a;
        if (a) {
          const nm = (m) => (m ? MOOD[m]?.name : 'no mood');
          el('auto').innerHTML = `<span>⚡ ${esc(a.reason)}: mood ${esc(nm(a.from))} → ${esc(nm(a.to))}</span><button class="btn small" data-ss="undoAuto">↶ Keep ${esc(nm(a.from))}</button>`;
        }

        // DM output controls.
        setVal(el('master'), au.master ?? 1);
        root.querySelectorAll('[data-output]').forEach((b) => {
          const on = (au.output || 'auto') === b.dataset.output;
          b.classList.toggle('on', on);
          b.setAttribute('aria-pressed', String(on));
        });
        el('autoCombat').checked = !!ss.autoCombat;
        el('lock').checked = !!ss.locked;
        const o = au.output || 'auto';
        el('where').textContent = o === 'tv' ? '🔈 plays on TV' : o === 'laptop' ? '🔈 plays on DM laptop' : s.screens ? '🔈 plays on TV' : '🔈 plays on DM laptop';
        el('by').textContent = ss.by ? `Last change by the ${ss.by}.${ss.by !== 'DM' && !helper ? ' Undo (Ctrl+Z) or any control here overrides it.' : ''}` : '';
      };
    },
  };
})();
