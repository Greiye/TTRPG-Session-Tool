// Builds the iso battle map from lib/iso-battle/src:
//   lib/iso-battle/dist/core.cjs  rules core for the server (require() from src/iso.js)
//   public/iso/iso-battle.js      browser module with Three.js bundled (no import map needed)
// Both outputs are committed, so `npm start` needs no build. Run `npm run build:iso` after editing lib/iso-battle/src.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = (p) => path.join(root, 'lib/iso-battle/src', p);
const banner = { js: '// Generated by tools/build-iso.mjs from lib/iso-battle/src. Do not edit by hand.' };

await build({ entryPoints: [src('core/index.js')], outfile: path.join(root, 'lib/iso-battle/dist/core.cjs'), bundle: true, platform: 'node', format: 'cjs', target: 'node20', banner, logLevel: 'info' });
await build({ entryPoints: [src('browser.js')], outfile: path.join(root, 'public/iso/iso-battle.js'), bundle: true, format: 'esm', target: 'es2022', minify: true, legalComments: 'eof', banner, logLevel: 'info' });
